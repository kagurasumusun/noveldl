std::string HttpClient::fetch(const std::string& url,
                              const std::optional<AccessSettings>& access,
                              const std::optional<std::string>& referer_url) {
    std::string host = url_host(url);
    if (host.empty()) throw Error("URL has no host: " + url);
    std::string profile =
        access && access->profile ? *access->profile : "chrome_desktop";

    // challenge fallback profiles: mobile <-> desktop swap
    std::vector<std::string> profiles{profile};
    if (profile == "safari_mobile") profiles.push_back("chrome_desktop");
    else if (profile == "chrome_desktop") profiles.push_back("safari_desktop");
    else profiles.push_back("safari_mobile");

    int retries = 3;
    int attempt = 0;
    while (true) {
        if (auto wait_ms = host_retry_window(host)) {
            std::this_thread::sleep_for(std::chrono::milliseconds(std::stoll(*wait_ms)));
        }
        try {
            // primary attempt
            std::string body;
            bool challenged = false;
            bool age_gate_attempted = false;
            try {
                HttpResponse resp =
                    transport_request(url, browser_headers(profiles[0], url, access, referer_url), 30);
                if (resp.status == 429) throw FetchError(FetchErrorKind::RateLimited, "429");
                if (resp.status == 503) throw FetchError(FetchErrorKind::Suspend, "503");
                if (resp.status == 404) throw FetchError(FetchErrorKind::NotFound, "404");
                // 年齢ゲート(「18歳以上ですか？」等)は confirm_over18 有効時に
                // 「はい」リンクを一度だけ自動クリックして通過を試みる。
                if (access && access->confirm_over18 && !age_gate_attempted &&
                    looks_like_age_gate(resp.body)) {
                    age_gate_attempted = true;
                    if (auto gate = age_gate_link(resp.body, access->age_gate_link_regex)) {
                        std::string gate_url = url_absolute(url, *gate);
                        std::string extra;
                        try {
                            HttpResponse g = transport_request(
                                gate_url,
                                browser_headers(profiles[0], gate_url, access, url), 30);
                            extra = cookie_header_from_set_cookies("", g.set_cookies);
                        } catch (...) {
                        }
                        auto hdrs2 = browser_headers(profiles[0], url, access, referer_url);
                        if (!extra.empty()) {
                            bool merged = false;
                            for (auto& kv : hdrs2) {
                                if (lower(kv.first) == "cookie") {
                                    kv.second += "; " + extra;
                                    merged = true;
                                }
                            }
                            if (!merged) hdrs2.emplace_back("Cookie", extra);
                        }
                        HttpResponse resp2 = transport_request(url, hdrs2, 30);
                        if (resp2.status >= 200 && resp2.status < 300 &&
                            !looks_like_age_gate(resp2.body))
                            return decode_body(resp2.body, "");
                    }
                    throw FetchError(FetchErrorKind::Challenge,
                                     "age confirmation gate (click-through failed)");
                }
                if (challenge_sample(resp.body, false))
                    throw FetchError(FetchErrorKind::Challenge, "challenge page");
                if (resp.status >= 200 && resp.status < 300) {
                    return decode_body(resp.body, "");
                }
                if (resp.status == 403) {
                    bool browser_fb = access && access->browser_fallback;
                    if (browser_fb || challenge_sample(resp.body, true))
                        throw FetchError(FetchErrorKind::Challenge, "403 challenge");
                    throw Error("forbidden response status=403");
                }
                throw Error("invalid response status=" + std::to_string(resp.status));
            } catch (const FetchError& e) {
                if (e.kind == FetchErrorKind::NotFound) throw;
                if (e.kind != FetchErrorKind::Challenge) throw;
                challenged = true;
            }
            if (challenged) {
                // secondary profiles
                for (size_t k = 1; k < profiles.size(); ++k) {
                    try {
                        HttpResponse resp = transport_request(
                            url, browser_headers(profiles[k], url, access, referer_url), 30);
                        if (challenge_sample(resp.body, false)) continue;
                        if (resp.status >= 200 && resp.status < 300)
                            return decode_body(resp.body, "");
                        if (resp.status == 403 && challenge_sample(resp.body, true)) continue;
                    } catch (const FetchError&) {
                        continue;
                    } catch (...) {
                        continue;
                    }
                }
                if (access && access->browser_fallback) {
                    if (auto cmd = browser_command()) {
                        return fetch_via_command(*cmd, url);
                    }
                }
                throw FetchError(FetchErrorKind::Challenge,
                                 "javascript challenge (enable browser fetch fallback?)");
            }
        } catch (const FetchError& e) {
            if (e.kind == FetchErrorKind::NotFound || e.kind == FetchErrorKind::Challenge)
                throw;
            bool rate_limited = e.kind == FetchErrorKind::RateLimited;
            if (retries <= 0) throw;
            --retries;
            ++attempt;
            int delay = retry_delay_ms(3000, attempt, rate_limited);
            remember_host_retry(host, delay);
            std::this_thread::sleep_for(std::chrono::milliseconds(delay));
            continue;
        } catch (const Error& e) {
            if (retries <= 0) throw;
            --retries;
            ++attempt;
            int delay = retry_delay_ms(3000, attempt, false);
            remember_host_retry(host, delay);
            std::this_thread::sleep_for(std::chrono::milliseconds(delay));
            continue;
        }
        break;
    }
    throw Error("fetch failed: " + url);
}

